"""Install a controller into the standard Webots project (machine-specific; run by each launcher).

    python install_controller.py --name custom_slam --source "<algo>/webots_controller/custom_slam.py" --python "<venv>/python.exe"
    python install_controller.py --name bench_supervisor --source "<std>/benchmark/bench_supervisor.py" --python ...

Creates webots/controllers/<name>/<name>.py (runs --source as __main__) and runtime.ini (so Webots
starts it with --python, the benchmark's own environment). Controller crashes are appended to
$SLAM_BENCH_RUN_DIR/../controller_errors.txt with the robot name, because Webots does not show
controller output in batch mode. The interpreter that ran each controller is logged too.
"""
import argparse
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

WRAPPER = r'''"""Generated by Standard Environment/tools/install_controller.py - do not edit."""
import os
import runpy
import sys
import time
import traceback

SOURCE = r"{source}"
sys.path.insert(0, os.path.dirname(SOURCE))
log_dir = os.path.dirname(os.environ.get('SLAM_BENCH_RUN_DIR', '')) or os.getcwd()
name = os.environ.get('WEBOTS_ROBOT_NAME', '?')
try:
    with open(os.path.join(log_dir, 'controllers_started.txt'), 'a') as f:
        f.write('%s {name} %s %s\n' % (time.strftime('%H:%M:%S'), name, sys.executable))
except OSError:
    pass
try:
    runpy.run_path(SOURCE, run_name='__main__')
except SystemExit:
    raise
except Exception:
    with open(os.path.join(log_dir, 'controller_errors.txt'), 'a') as f:
        f.write('--- {name} %s ---\n%s\n' % (name, traceback.format_exc()))
    raise
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--name', required=True)
    ap.add_argument('--source', required=True)
    ap.add_argument('--python', required=True)
    args = ap.parse_args()
    d = os.path.join(ROOT, 'webots', 'controllers', args.name)
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, args.name+'.py'), 'w') as f:
        f.write(WRAPPER.format(source=os.path.abspath(args.source), name=args.name))
    with open(os.path.join(d, 'runtime.ini'), 'w') as f:
        f.write('; Generated: run this controller with the benchmark Python environment.\n[python]\nCOMMAND = %s\n'
                % os.path.abspath(args.python))
    print('installed controller', args.name)


if __name__ == '__main__':
    main()
